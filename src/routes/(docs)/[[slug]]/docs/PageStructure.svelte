<h1>Page Structure</h1>

<p>A marketing page should have a header, a footer, and a main content area:</p>

<ul>
	<li>
		<a href="/header"><code>{'<Header>'}</code></a>: the site header, before
		<code>{'<Base>'}</code>.
	</li>
	<li>
		<a href="/homepage-components">Homepage Components</a>: content sections stacked inside
		<code>{'<Base>'}</code>: <code>{'<Hero>'}</code>, <code>{'<LogoStrip>'}</code>,
		<code>{'<FeatureSplit>'}</code>, <code>{'<Testimonials>'}</code>,
		<code>{'<AllFeaturesAccordion>'}</code>, <code>{'<FAQ>'}</code>,
		<code>{'<FullTrialSignup>'}</code>, and <code>{'<SpotlightSplit>'}</code>.
	</li>
	<li>
		<a href="/footer"><code>{'<Footer>'}</code></a>: the site footer, after
		<code>{'<Base>'}</code>.
	</li>
	<li>
		<a href="/details-accordion">Details Accordion</a>: a standalone expand/collapse component,
		usable anywhere on the page.
	</li>
</ul>

<p>
