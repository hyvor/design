<h1>HYVOR Design System</h1>

<p>
	Hyvor Design System, HDS, is a collection of Svelte UI components for building HYVOR products. It
	is open-source and you can view the source code on Github. However, it is not recommended to use
	HDS on non-HYVOR projects as it is not designed to be a general-purpose UI library.
</p>
